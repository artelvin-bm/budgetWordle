    private void tryButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tryButtonActionPerformed
        JLabel[] guesses
                = {guess1, guess2, guess3,
                    guess4, guess5, guess6};

        String guess = tryText.getText();

        int guessWordCount = tryText.getText().length();

        for (JLabel label : guesses) {
            if (Jsoup.parse(label.getText()).text().isEmpty()) {
                if (guess.isEmpty() || guess.isBlank()) {
                    invalidTryText.setText("Please enter a 5-letter word.");
                    invalidTryDialog.setVisible(true);
                    break;
                }
                if (guessWordCount != 5 && !guess.matches("[a-zA-Z]+")) {
                    invalidTryText.setText("Non-5-letter word and non-letter characters found.");
                    invalidTryDialog.setVisible(true);
                    break;
                } else if (guessWordCount != 5) {
                    invalidTryText.setText("You did not enter a 5-letter word.");
                    invalidTryDialog.setVisible(true);
                    break;
                } else if (!guess.matches("[a-zA-Z]+")) {
                    invalidTryText.setText("The word you entered contains non-letter characters.");
                    invalidTryDialog.setVisible(true);
                    break;
                } else {
                    String guessColorized = guessChecker.colorizeGuess(randomWord, guess.toLowerCase());
                    label.setText(guessColorized.toUpperCase());

                    if (guess.toLowerCase().equals(randomWord.toLowerCase())) {
                        failCount = 0;
                        victoryDialog.setVisible(true);
                    } else {
                        failCount++;
                    }
                    break;
                }
            }
        }

        if (failCount == 6) {
            defeatDialog.setLocationRelativeTo(null);
            jLabel3.setText(randomWord.toUpperCase());
            defeatDialog.setVisible(true);
        }
        tryText.setText("");
    }//GEN-LAST:event_tryButtonActionPerformed

